import { ChangeDetectionStrategy, Component, computed, inject, signal } from '@angular/core';
import { takeUntilDestroyed, toSignal } from '@angular/core/rxjs-interop';
import {
    AbstractControl,
    FormControl,
    FormGroup,
    ReactiveFormsModule,
    ValidationErrors,
    Validators,
} from '@angular/forms';
import { Router } from '@angular/router';
import { MatButtonModule } from '@angular/material/button';
import { MatError, MatFormField, MatHint, MatLabel } from '@angular/material/form-field';
import { MatInput } from '@angular/material/input';
import { MatOption, MatSelect } from '@angular/material/select';
import { MatProgressSpinner } from '@angular/material/progress-spinner';
import { MatSnackBar } from '@angular/material/snack-bar';
import { TranslatePipe, TranslateService } from '@ngx-translate/core';
import {
    SPECIALTIES,
    Specialty,
    toSpecialtyKebabCase,
} from '../../../../shared/domain/model/specialty';
import { InventoryStore } from '../../../application/inventory.store';
import { BookStock } from '../../../domain/model/book-stock.entity';
import { BookstoresStore } from '../../../../bookstores/application/bookstores.store';
import { CatalogStore } from '../../../../catalog/application/catalog.store';
import { BookSummary } from '../../../../catalog/presentation/components/book-summary/book-summary';

/**
 * Receive Books view: reactive form to register a book stock.
 *
 * @remarks
 * The user selects a specialty, then a book from the Open Library catalog of that specialty,
 * and enters the copies. The bookstore is determined by the specialty, `receivedAt` is set to
 * the current date and time, and `id` is generated by the backend. Copies must be an integer
 * greater than zero and less than or equal to twice the bookstore minimum copies.
 *
 * @author Sebastian Uriel Becerra Durand
 */
@Component({
    selector: 'app-book-receipt-form',
    imports: [
        ReactiveFormsModule,
        MatFormField,
        MatLabel,
        MatError,
        MatHint,
        MatInput,
        MatSelect,
        MatOption,
        MatButtonModule,
        MatProgressSpinner,
        TranslatePipe,
        BookSummary,
    ],
    templateUrl: './book-receipt-form.html',
    styleUrl: './book-receipt-form.css',
    changeDetection: ChangeDetectionStrategy.OnPush,
})
export class BookReceiptForm {
    readonly #router = inject(Router);
    readonly #snackBar = inject(MatSnackBar);
    readonly #translate = inject(TranslateService);
    readonly #inventoryStore = inject(InventoryStore);
    readonly #bookstoresStore = inject(BookstoresStore);
    readonly #SNACKBAR_DURATION_MS = 3000;

    /** Catalog store, exposed for loading and error state. */
    protected readonly catalogStore = inject(CatalogStore);

    /** Supported specialties. */
    protected readonly specialties = SPECIALTIES;

    /** Converts a specialty into its kebab-case translation identifier. */
    protected readonly toSpecialtyKebabCase = toSpecialtyKebabCase;

    /** Book receipt form. The book is enabled after a specialty is chosen. */
    protected readonly form = new FormGroup({
        specialty: new FormControl<Specialty | null>(null, { validators: [Validators.required] }),
        bookKey: new FormControl<string | null>(
            { value: null, disabled: true },
            { validators: [Validators.required] },
        ),
        copies: new FormControl<number | null>(null, {
            validators: [Validators.required, (control: AbstractControl) => this.#copiesValidator(control)],
        }),
    });

    /** Currently selected specialty. */
    protected readonly selectedSpecialty = toSignal(this.form.controls.specialty.valueChanges, {
        initialValue: null,
    });

    /** Currently selected book key. */
    protected readonly selectedBookKey = toSignal(this.form.controls.bookKey.valueChanges, {
        initialValue: null,
    });

    /** Bookstore assigned to the selected specialty. */
    protected readonly selectedBookstore = computed(() =>
        this.#bookstoresStore.getBookstoreBySpecialty(this.selectedSpecialty())(),
    );

    /** Books of the selected specialty. */
    protected readonly books = computed(() =>
        this.catalogStore.getBooksBySpecialty(this.selectedSpecialty())(),
    );

    /** Selected book. */
    protected readonly selectedBook = computed(() =>
        this.catalogStore.getBookByKey(this.selectedSpecialty(), this.selectedBookKey())(),
    );

    /** Whether the registration request is in progress. */
    protected readonly saving = signal(false);

    /** Translation key of the last registration error, if any. */
    protected readonly submitErrorKey = signal<string | null>(null);

    /** Loads the books and enables the book selection when a specialty is selected. */
    constructor() {
        this.form.controls.specialty.valueChanges
            .pipe(takeUntilDestroyed())
            .subscribe((specialty) => {
                const bookControl = this.form.controls.bookKey;
                bookControl.reset();
                if (specialty) {
                    this.catalogStore.loadBooksBySpecialty(specialty);
                    bookControl.enable();
                } else {
                    bookControl.disable();
                }
                this.form.controls.copies.updateValueAndValidity();
                this.submitErrorKey.set(null);
            });
    }

    /**
     * Checks whether a control is invalid and was touched.
     * @param controlName - Control name.
     */
    protected isInvalidControl(controlName: 'specialty' | 'bookKey' | 'copies'): boolean {
        const control = this.form.controls[controlName];
        return control.invalid && control.touched;
    }

    /** Registers the book stock and, once completed, returns to Bookstore Overview. */
    protected receive(): void {
        this.form.markAllAsTouched();
        const bookstore = this.selectedBookstore();
        const book = this.selectedBook();
        const copies = Number(this.form.controls.copies.value);
        if (this.form.invalid || !bookstore || !book || !bookstore.canReceive(copies)) return;

        const bookStock = new BookStock({
            id: 0,
            bookstoreId: bookstore.id,
            bookKey: book.key,
            bookTitle: book.title,
            authorName: book.authorName,
            copies,
            receivedAt: new Date(),
        });

        this.saving.set(true);
        this.submitErrorKey.set(null);
        this.#inventoryStore.addBookStock(bookStock).subscribe({
            next: () => {
                this.saving.set(false);
                this.#snackBar.open(
                    this.#translate.instant('book-receipt.received'),
                    this.#translate.instant('book-receipt.close'),
                    { duration: this.#SNACKBAR_DURATION_MS },
                );
                this.#navigateToOverview();
            },
            error: () => {
                this.saving.set(false);
                this.submitErrorKey.set('book-receipt.error.save-failed');
            },
        });
    }

    /** Discards the form and returns to Bookstore Overview. */
    protected cancel(): void {
        this.form.reset();
        this.#navigateToOverview();
    }

    #copiesValidator(control: AbstractControl): ValidationErrors | null {
        if (control.value === null || control.value === '') return null;
        const copies = Number(control.value);
        if (!Number.isInteger(copies) || copies <= 0) return { copiesInvalid: true };
        const bookstore = this.selectedBookstore?.();
        if (bookstore && !bookstore.canReceive(copies)) {
            return { copiesRange: { max: bookstore.maximumCopiesPerReceipt } };
        }
        return null;
    }

    #navigateToOverview(): void {
        this.#router.navigate(['/bookstores/overview']).then();
    }
}
